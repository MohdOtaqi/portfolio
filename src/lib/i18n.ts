export type Locale = "en" | "ar";
export const LOCALES: Locale[] = ["en", "ar"];

/** Prefix an internal path with the locale ("/ar" for Arabic, nothing for English). */
export function href(locale: Locale, path: string) {
  if (locale === "en") return path || "/";
  if (!path || path === "/") return "/ar";
  return `/ar${path.startsWith("/") ? path : `/${path}`}`;
}

/** The same page in the other language. */
export function switchHref(locale: Locale, path: string) {
  const bare = locale === "ar" ? path.replace(/^\/ar(?=\/|$)/, "") || "/" : path;
  return href(locale === "ar" ? "en" : "ar", bare);
}

